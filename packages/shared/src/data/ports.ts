export type Region =
  | 'Northern Europe'
  | 'Mediterranean & Black Sea'
  | 'Africa'
  | 'Middle East & South Asia'
  | 'East & Southeast Asia'
  | 'Oceania'
  | 'North America'
  | 'Central & South America';

const REGION_PORTS: Record<Region, string[]> = {
  'Northern Europe': ['ham', 'rtm', 'lon', 'cph'],
  'Mediterranean & Black Sea': ['gen', 'pir', 'alx', 'ist', 'ods'],
  Africa: ['lag', 'cpt', 'mba'],
  'Middle East & South Asia': ['jed', 'dxb', 'khi', 'bom', 'cmb'],
  'East & Southeast Asia': ['sin', 'jkt', 'lcb', 'sgn', 'mnl', 'hkg', 'khh', 'sha', 'pus', 'yok'],
  Oceania: ['syd', 'akl'],
  'North America': ['van', 'lax', 'hou', 'nyc', 'hfx', 'mtl'],
  'Central & South America': ['ctg', 'lgu', 'geo', 'pbm', 'gye', 'cll', 'vap', 'rio', 'mvd', 'bue'],
};

export const REGIONS = Object.keys(REGION_PORTS) as Region[];
const REGION_OF: Record<string, Region> = Object.fromEntries(
  REGIONS.flatMap((r) => REGION_PORTS[r].map((id) => [id, r])),
);

/** The region a port belongs to, for grouping port lists. */
export function portRegion(id: string): Region {
  return REGION_OF[id];
}

/** Ports grouped by region (in display order), each group sorted by name. */
export function portsByRegion(): [Region, Port[]][] {
  return REGIONS.map((r) => [
    r,
    PORTS.filter((x) => REGION_OF[x.id] === r).sort((a, b) => a.name.localeCompare(b.name)),
  ]);
}

export const PORTS_BY_ID: Record<string, Port> = Object.fromEntries(PORTS.map((x) => [x.id, x]));

export function getPort(id: string): Port {
  const port = PORTS_BY_ID[id];
  if (!port) throw new Error(`Unknown port ${id}`);
  return port;
}

